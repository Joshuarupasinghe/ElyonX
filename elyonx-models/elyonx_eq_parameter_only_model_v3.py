def stratified_split_records(records, train_ratio=0.70, val_ratio=0.15, test_ratio=0.15):
    train, val, test = [], [], []
    rng = random.Random(SEED)

    for inst in INSTRUMENTS:
        inst_records = [r for r in records if r['instrument'] == inst]
        rng.shuffle(inst_records)
        n = len(inst_records)
        if n == 0:
            continue

        if n < 4:
            # Very small fallback: keep at least train, use test only if possible.
            n_train = max(1, int(round(n * train_ratio)))
            n_val = 0 if n < 3 else 1
            n_test = n - n_train - n_val
        else:
            n_train = max(1, int(round(n * train_ratio)))
            n_val = max(1, int(round(n * val_ratio)))
            n_test = n - n_train - n_val
            if n_test <= 0:
                n_test = 1
                n_train = max(1, n_train - 1)

        train.extend(inst_records[:n_train])
        val.extend(inst_records[n_train:n_train+n_val])
        test.extend(inst_records[n_train+n_val:])

    rng.shuffle(train)
    rng.shuffle(val)
    rng.shuffle(test)
    return train, val, test


