def predict_eq_params_from_audio(y: np.ndarray, instrument: str = 'kick'):
    assert instrument in INST_TO_IDX, f"instrument must be one of {INSTRUMENTS}"
    model.eval()
    features = extract_rta_features(y, sr=SR)
    features_scaled = scaler.transform(features.reshape(1, -1)).astype(np.float32)
    x = torch.from_numpy(features_scaled).float().to(DEVICE)
    inst = torch.tensor([INST_TO_IDX[instrument]], dtype=torch.long, device=DEVICE)
    with torch.no_grad():
        pred_norm = model(x, inst).cpu().numpy().squeeze(0)
    return normalized_to_params(pred_norm)


def params_to_dataframe(params):
    rows = []
    for b_idx, band in enumerate(EQ_BANDS):
        gain, freq, q = params[b_idx]
        action = 'Boost' if gain > 1.0 else 'Cut' if gain < -1.0 else 'Flat / no major change'
        rows.append({
            'Band': band['name'],
            'Action': action,
            'Gain dB': float(gain),
            'Frequency Hz': float(freq),
            'Q': float(q),
        })
    return pd.DataFrame(rows)

