class EQParamPredictor(nn.Module):
    def __init__(self, feature_dim: int, n_instruments: int, out_dim: int):
        super().__init__()
        self.inst_embedding = nn.Embedding(n_instruments, 16)
        self.net = nn.Sequential(
            nn.Linear(feature_dim + 16, 256),
            nn.LayerNorm(256),
            nn.LeakyReLU(0.15),
            nn.Dropout(0.20),

            nn.Linear(256, 192),
            nn.LayerNorm(192),
            nn.LeakyReLU(0.15),
            nn.Dropout(0.15),

            nn.Linear(192, 128),
            nn.LayerNorm(128),
            nn.LeakyReLU(0.15),
            nn.Dropout(0.10),

            nn.Linear(128, out_dim),
            nn.Tanh(),  # normalized output remains in [-1, +1]
        )

    def forward(self, features, inst_id):
        emb = self.inst_embedding(inst_id)
        x = torch.cat([features, emb], dim=1)
        return self.net(x)


