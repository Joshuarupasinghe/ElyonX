"""## 4. Automatic EQ label fitting

This section creates labels automatically.

The target EQ curve is calculated from the spectral ratio:

```text
target EQ curve = EQ'd spectrum / raw spectrum
```

Then a 6-band parametric EQ is optimized to match that curve.

Each band produces:

```text
[gain dB, frequency Hz, Q]
```

Negative gain means **cut**. Positive gain means **boost**.
"""

# ============================================================
# 5. Parametric EQ response and label fitting
# ============================================================


def average_magnitude_spectrum(y: np.ndarray, sr: int = SR, n_fft: int = 4096, hop_length: int = 1024):
    if len(y) < n_fft:
        y = np.pad(y, (0, n_fft - len(y)))
    S = np.abs(librosa.stft(y, n_fft=n_fft, hop_length=hop_length, window='hann', center=True))
    mag = np.median(S, axis=1) + EPS
    freqs = librosa.fft_frequencies(sr=sr, n_fft=n_fft)
    return freqs, mag


def peaking_eq_response(freqs: np.ndarray, sr: int, f0: float, gain_db: float, q: float):
    """RBJ peaking EQ magnitude response."""
    f0 = float(np.clip(f0, 1.0, sr / 2.0 - 1.0))
    q = float(np.clip(q, Q_MIN, Q_MAX))
    A = 10.0 ** (gain_db / 40.0)
    w0 = 2.0 * np.pi * f0 / sr
    alpha = np.sin(w0) / (2.0 * q)
    cos_w0 = np.cos(w0)

    b0 = 1.0 + alpha * A
    b1 = -2.0 * cos_w0
    b2 = 1.0 - alpha * A
    a0 = 1.0 + alpha / A
    a1 = -2.0 * cos_w0
    a2 = 1.0 - alpha / A

    b0, b1, b2 = b0 / a0, b1 / a0, b2 / a0
    a1, a2 = a1 / a0, a2 / a0

    w = 2.0 * np.pi * freqs / sr
    z1 = np.exp(-1j * w)
    z2 = np.exp(-2j * w)
    h = (b0 + b1 * z1 + b2 * z2) / (1.0 + a1 * z1 + a2 * z2)
    return h


def params_to_curve_db(params: np.ndarray, freqs: np.ndarray, sr: int = SR):
    """params shape: (N_BANDS, 3) where columns = gain_db, freq_hz, Q."""
    h_total = np.ones_like(freqs, dtype=np.complex128)
    for gain_db, f0, q in params:
        h_total *= peaking_eq_response(freqs, sr, f0, gain_db, q)
    return 20.0 * np.log10(np.abs(h_total) + EPS)


def initial_params_from_ratio(freqs, ratio_db):
    init = []
    for band in EQ_BANDS:
        lo, hi = band['min_hz'], band['max_hz']
        mask = (freqs >= lo) & (freqs <= hi)
        if mask.any():
            band_freqs = freqs[mask]
            band_ratio = ratio_db[mask]
            # Start from the most changed frequency in that band.
            idx = int(np.argmax(np.abs(band_ratio)))
            gain0 = float(np.clip(band_ratio[idx], -MAX_GAIN_DB, MAX_GAIN_DB))
            f0 = float(np.clip(band_freqs[idx], lo, hi))
        else:
            gain0 = 0.0
            f0 = band['init_hz']
        q0 = 1.20
        init.extend([gain0, np.log(f0), np.log(q0)])
    return np.array(init, dtype=np.float64)


def vector_to_params(vec):
    params = []
    for i, band in enumerate(EQ_BANDS):
        gain_db = vec[i * 3 + 0]
        f0 = np.exp(vec[i * 3 + 1])
        q = np.exp(vec[i * 3 + 2])
        gain_db = float(np.clip(gain_db, -MAX_GAIN_DB, MAX_GAIN_DB))
        f0 = float(np.clip(f0, band['min_hz'], band['max_hz']))
        q = float(np.clip(q, Q_MIN, Q_MAX))
        params.append([gain_db, f0, q])
    return np.array(params, dtype=np.float32)


def build_bounds():
    lower, upper = [], []
    for band in EQ_BANDS:
        lower.extend([-MAX_GAIN_DB, np.log(band['min_hz']), np.log(Q_MIN)])
        upper.extend([+MAX_GAIN_DB, np.log(band['max_hz']), np.log(Q_MAX)])
    return np.array(lower, dtype=np.float64), np.array(upper, dtype=np.float64)


def weighted_mean(values, weights):
    return float(np.sum(values * weights) / (np.sum(weights) + EPS))


def fit_eq_params_from_pair(raw: np.ndarray, eq: np.ndarray, sr: int = SR, plot: bool = False):
    freqs, raw_mag = average_magnitude_spectrum(raw, sr=sr, n_fft=4096, hop_length=1024)
    _, eq_mag = average_magnitude_spectrum(eq, sr=sr, n_fft=4096, hop_length=1024)

    valid = (freqs >= FEATURE_FMIN) & (freqs <= min(FEATURE_FMAX, sr / 2.0 - 100.0))
    freqs_v = freqs[valid]
    raw_mag_v = raw_mag[valid]
    eq_mag_v = eq_mag[valid]

    ratio_db = 20.0 * np.log10((eq_mag_v + EPS) / (raw_mag_v + EPS))
    ratio_db = medfilt(ratio_db, kernel_size=5)
    ratio_db = gaussian_filter1d(ratio_db, sigma=1.2)
    ratio_db = np.clip(ratio_db, -MAX_GAIN_DB, MAX_GAIN_DB)

    # Frequency weights: emphasize frequencies that exist in the raw signal.
    weights = np.sqrt(raw_mag_v / (np.max(raw_mag_v) + EPS))
    weights = np.clip(weights, 0.08, 1.0)

    # Remove pure volume difference so the model learns EQ shape, not makeup gain.
    global_gain_removed = 0.0
    if REMOVE_GLOBAL_GAIN_FROM_LABELS:
        global_gain_removed = weighted_mean(ratio_db, weights)
        ratio_db = ratio_db - global_gain_removed
        ratio_db = np.clip(ratio_db, -MAX_GAIN_DB, MAX_GAIN_DB)

    x0 = initial_params_from_ratio(freqs_v, ratio_db)
    lb, ub = build_bounds()

    def residual(vec):
        p = vector_to_params(vec)
        pred_curve = params_to_curve_db(p, freqs_v, sr=sr)
        main = (pred_curve - ratio_db) * weights
        # Tiny regularizer to avoid unnecessary extreme filters.
        gains = np.array([p[i, 0] for i in range(N_BANDS)], dtype=np.float64)
        reg = 0.015 * gains / MAX_GAIN_DB
        return np.concatenate([main, reg])

    result = least_squares(
        residual,
        x0,
        bounds=(lb, ub),
        max_nfev=LABEL_FIT_MAX_NFEV,
        xtol=1e-9,
        ftol=1e-9,
        gtol=1e-9,
        verbose=0,
    )

    fitted_params = vector_to_params(result.x)
    fitted_curve = params_to_curve_db(fitted_params, freqs_v, sr=sr)

    fit_mae_db = float(np.mean(np.abs(fitted_curve - ratio_db)))
    fit_rmse_db = float(np.sqrt(np.mean((fitted_curve - ratio_db) ** 2)))
    fit_max_abs_db = float(np.max(np.abs(fitted_curve - ratio_db)))

    if plot:
        plt.figure(figsize=(10, 4))
        plt.semilogx(freqs_v, ratio_db, label='Target spectral ratio', linewidth=1.2)
        plt.semilogx(freqs_v, fitted_curve, label='Fitted parametric EQ', linewidth=1.2)
        plt.axhline(0, linewidth=0.6)
        plt.xlabel('Frequency (Hz)')
        plt.ylabel('Gain (dB)')
        plt.title(f'Auto-fitted EQ label | MAE={fit_mae_db:.2f} dB')
        plt.grid(True, which='both', alpha=0.25)
        plt.legend()
        plt.tight_layout()
        plt.show()

    return fitted_params, {
        "fit_mae_db": fit_mae_db,
        "fit_rmse_db": fit_rmse_db,
        "fit_max_abs_db": fit_max_abs_db,
        "global_gain_removed_db": global_gain_removed,
        "optimizer_success": bool(result.success),
        "optimizer_cost": float(result.cost),
        "optimizer_nfev": int(result.nfev),
    }

