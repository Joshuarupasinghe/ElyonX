LIVE_EMA_ALPHA = 0.75  # higher = smoother/slower changes


def live_rta_loop(instrument='kick', seconds_per_read=0.50, sample_rate=SR, device_index=None, iterations=20):
    """Capture microphone audio and print smoothed EQ recommendations."""
    assert instrument in INST_TO_IDX, f"instrument must be one of {INSTRUMENTS}"
    try:
        import sounddevice as sd
    except Exception as e:
        raise RuntimeError("Install sounddevice first: pip install sounddevice") from e

    smoothed_params = None
    frames = int(seconds_per_read * sample_rate)

    for i in range(iterations):
        audio = sd.rec(frames, samplerate=sample_rate, channels=1, dtype='float32', device=device_index)
        sd.wait()
        y = audio[:, 0]

        params = predict_eq_params_from_audio(y, instrument=instrument)
        if smoothed_params is None:
            smoothed_params = params
        else:
            smoothed_params = LIVE_EMA_ALPHA * smoothed_params + (1.0 - LIVE_EMA_ALPHA) * params

        print('\n' + '=' * 80)
        print(f'Live EQ recommendation {i+1}/{iterations} | Instrument: {instrument}')
        display(params_to_dataframe(smoothed_params))

