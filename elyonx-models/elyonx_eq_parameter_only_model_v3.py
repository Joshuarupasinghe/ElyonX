EPS = 1e-9


def rms(x: np.ndarray) -> float:
    return float(np.sqrt(np.mean(np.square(x)) + EPS))


def dbfs_from_rms(x: np.ndarray) -> float:
    return 20.0 * np.log10(rms(x) + EPS)


def dbfs_from_peak(x: np.ndarray) -> float:
    return 20.0 * np.log10(float(np.max(np.abs(x))) + EPS)


def load_audio_mono(path: Path, sr: int = SR) -> np.ndarray:
    y, _ = librosa.load(str(path), sr=sr, mono=True)
    y = np.asarray(y, dtype=np.float32)
    y = np.nan_to_num(y, nan=0.0, posinf=0.0, neginf=0.0)
    return y


def trim_pair(raw: np.ndarray, eq: np.ndarray, sr: int = SR):
    """Trim raw/EQ together using a shared activity envelope."""
    min_len = min(len(raw), len(eq))
    raw = raw[:min_len]
    eq = eq[:min_len]
    if min_len == 0:
        return raw, eq, 0, 0

    combined = np.maximum(np.abs(raw), np.abs(eq))
    peak = float(combined.max())
    if peak < EPS:
        return raw[:0], eq[:0], 0, 0

    threshold = peak * (10.0 ** (-TRIM_TOP_DB / 20.0))
    active = np.where(combined > threshold)[0]
    if len(active) == 0:
        return raw[:0], eq[:0], 0, 0

    margin = int(TRIM_MARGIN_SEC * sr)
    start = max(0, int(active[0]) - margin)
    end = min(min_len, int(active[-1]) + margin + 1)
    return raw[start:end], eq[start:end], start, end


def pairwise_normalize(raw: np.ndarray, eq: np.ndarray):
    """Normalize raw to TARGET_RMS_DBFS and apply the same factor to EQ target."""
    target_rms = 10.0 ** (TARGET_RMS_DBFS / 20.0)
    raw_rms = rms(raw)
    scale = target_rms / (raw_rms + EPS)

    peak_after = max(float(np.max(np.abs(raw * scale))), float(np.max(np.abs(eq * scale))), EPS)
    if peak_after > MAX_ALLOWED_PEAK:
        scale *= MAX_ALLOWED_PEAK / peak_after

    return (raw * scale).astype(np.float32), (eq * scale).astype(np.float32), float(scale)


def active_duration_sec(y: np.ndarray, sr: int = SR, top_db: float = 45.0) -> float:
    if len(y) == 0:
        return 0.0
    peak = float(np.max(np.abs(y)))
    if peak < EPS:
        return 0.0
    threshold = peak * (10.0 ** (-top_db / 20.0))
    active = np.where(np.abs(y) > threshold)[0]
    if len(active) == 0:
        return 0.0
    return float((active[-1] - active[0] + 1) / sr)


def clipping_percent(y: np.ndarray, threshold: float = 0.999) -> float:
    if len(y) == 0:
        return 0.0
    return float(np.mean(np.abs(y) >= threshold) * 100.0)

