"""## 5. Feature extraction for live RTA mic use

The model input is not raw waveform output. It learns from RTA-like spectral features:

- 128 log-spaced magnitude bands
- RMS / peak level
- spectral centroid
- spectral bandwidth
- spectral flatness
- zero-crossing rate

This is closer to how a live RTA microphone would observe the signal.
"""

# ============================================================
# 7. RTA feature extraction
# ============================================================

RTA_BIN_EDGES = np.geomspace(FEATURE_FMIN, FEATURE_FMAX, N_RTA_BINS + 1)


def crop_or_pad(y: np.ndarray, length: int = WINDOW_SIZE):
    y = np.asarray(y, dtype=np.float32)
    if len(y) == length:
        return y
    if len(y) < length:
        pad_total = length - len(y)
        left = pad_total // 2
        right = pad_total - left
        return np.pad(y, (left, right)).astype(np.float32)
    # center around the highest energy region
    frame = min(1024, len(y))
    hop = frame // 2
    if len(y) <= frame:
        start = 0
    else:
        energies = []
        starts = range(0, len(y) - frame + 1, hop)
        for s in starts:
            energies.append(np.mean(y[s:s+frame] ** 2))
        best = int(np.argmax(energies))
        center = best * hop + frame // 2
        start = max(0, min(center - length // 2, len(y) - length))
    return y[start:start+length].astype(np.float32)


def normalize_for_features(y: np.ndarray):
    """Normalize level for feature extraction without changing labels."""
    y = np.asarray(y, dtype=np.float32)
    if len(y) == 0:
        return y
    current = rms(y)
    target = 10.0 ** (TARGET_RMS_DBFS / 20.0)
    z = y * (target / (current + EPS))
    peak = float(np.max(np.abs(z))) + EPS
    if peak > MAX_ALLOWED_PEAK:
        z = z * (MAX_ALLOWED_PEAK / peak)
    return z.astype(np.float32)


def extract_rta_features(y: np.ndarray, sr: int = SR):
    y = crop_or_pad(y, WINDOW_SIZE)
    y = normalize_for_features(y)

    window = np.hanning(len(y)).astype(np.float32)
    spectrum = np.abs(np.fft.rfft(y * window, n=FFT_SIZE)) + EPS
    freqs = np.fft.rfftfreq(FFT_SIZE, d=1.0 / sr)

    band_values = []
    for lo, hi in zip(RTA_BIN_EDGES[:-1], RTA_BIN_EDGES[1:]):
        mask = (freqs >= lo) & (freqs < hi)
        if mask.any():
            val = np.sqrt(np.mean(np.square(spectrum[mask])))
        else:
            val = EPS
        band_values.append(20.0 * np.log10(val + EPS))
    band_values = np.asarray(band_values, dtype=np.float32)

    # Shape normalization: live mic absolute level can change, so remove median spectral level.
    band_shape = band_values - np.median(band_values)
    band_shape = np.clip(band_shape, -60.0, 60.0)

    rms_db = dbfs_from_rms(y)
    peak_db = dbfs_from_peak(y)

    try:
        centroid = float(librosa.feature.spectral_centroid(y=y, sr=sr, n_fft=2048, hop_length=512).mean()) / (sr / 2)
        bandwidth = float(librosa.feature.spectral_bandwidth(y=y, sr=sr, n_fft=2048, hop_length=512).mean()) / (sr / 2)
        flatness = float(librosa.feature.spectral_flatness(y=y, n_fft=2048, hop_length=512).mean())
        zcr = float(librosa.feature.zero_crossing_rate(y, frame_length=2048, hop_length=512).mean())
    except Exception:
        centroid, bandwidth, flatness, zcr = 0.0, 0.0, 0.0, 0.0

    extra = np.array([rms_db / 60.0, peak_db / 60.0, centroid, bandwidth, flatness, zcr], dtype=np.float32)
    return np.concatenate([band_shape.astype(np.float32), extra]).astype(np.float32)


def peak_limit(y: np.ndarray, max_peak: float = MAX_ALLOWED_PEAK):
    y = np.nan_to_num(np.asarray(y, dtype=np.float32), nan=0.0, posinf=0.0, neginf=0.0)
    peak = float(np.max(np.abs(y))) + EPS if len(y) else EPS
    if peak > max_peak:
        y = y * (max_peak / peak)
    return y.astype(np.float32)


def make_synthetic_room_ir(sr: int, rng: np.random.Generator):
    length_ms = float(rng.uniform(*ROOM_IR_LENGTH_MS))
    decay_ms = float(rng.uniform(*ROOM_IR_DECAY_MS))
    length = max(64, int(sr * length_ms / 1000.0))
    ir = np.zeros(length, dtype=np.float32)
    ir[0] = 1.0

    n_reflections = int(rng.integers(ROOM_EARLY_REFLECTIONS[0], ROOM_EARLY_REFLECTIONS[1] + 1))
    for _ in range(n_reflections):
        delay_ms = float(rng.uniform(3.0, min(90.0, length_ms * 0.75)))
        delay = min(length - 1, max(1, int(sr * delay_ms / 1000.0)))
        decay = np.exp(-delay_ms / max(decay_ms, EPS))
        ir[delay] += float(rng.uniform(-0.45, 0.45) * decay)

    tail_start = min(length - 1, max(1, int(sr * float(rng.uniform(12.0, 35.0)) / 1000.0)))
    tail_t = np.arange(length - tail_start, dtype=np.float32) / sr
    tail_decay = np.exp(-tail_t / max(decay_ms / 1000.0, EPS))
    ir[tail_start:] += (
        rng.normal(0.0, 0.08, size=length - tail_start).astype(np.float32)
        * tail_decay.astype(np.float32)
    )

    ir = peak_limit(ir, max_peak=1.0)
    energy = float(np.sqrt(np.sum(np.square(ir))) + EPS)
    return (ir / energy).astype(np.float32)


def apply_room_tilt(y: np.ndarray, sr: int, rng: np.random.Generator):
    if len(y) == 0:
        return y.astype(np.float32)

    tilt_db = float(rng.uniform(-ROOM_TILT_MAX_DB, ROOM_TILT_MAX_DB))
    freqs = np.fft.rfftfreq(len(y), d=1.0 / sr)
    scale_db = tilt_db * np.log2(np.maximum(freqs, 30.0) / 1000.0)
    scale_db = np.clip(scale_db, -6.0, 6.0)
    spectrum = np.fft.rfft(y)
    tilted = np.fft.irfft(spectrum * (10.0 ** (scale_db / 20.0)), n=len(y))
    return peak_limit(tilted)


def add_background_noise(y: np.ndarray, rng: np.random.Generator):
    if len(y) == 0:
        return y.astype(np.float32)

    snr_db = float(rng.uniform(*ROOM_NOISE_SNR_DB))
    noise = rng.normal(0.0, 1.0, size=len(y)).astype(np.float32)
    target_noise_rms = rms(y) / (10.0 ** (snr_db / 20.0))
    noise = noise * (target_noise_rms / (rms(noise) + EPS))
    return peak_limit(y + noise)


def simulate_room_acoustics(y: np.ndarray, sr: int = SR, rng: Optional[np.random.Generator] = None):
    """Create an RTA-mic-like variant while keeping the same EQ target labels."""
    rng = rng or np.random.default_rng()
    clean = np.asarray(y, dtype=np.float32)
    if len(clean) == 0:
        return clean

    ir = make_synthetic_room_ir(sr, rng)
    wet = fftconvolve(clean, ir, mode='full')[: len(clean)].astype(np.float32)
    wet_mix = float(rng.uniform(*ROOM_WET_MIX))
    augmented = (1.0 - wet_mix) * clean + wet_mix * wet
    augmented = apply_room_tilt(augmented, sr, rng)

    if rng.random() < ROOM_BLEED_PROB:
        delay = int(sr * float(rng.uniform(0.015, 0.090)))
        if 0 < delay < len(clean):
            bleed = np.zeros_like(clean)
            bleed[delay:] = clean[:-delay] * float(rng.uniform(*ROOM_BLEED_GAIN))
            bleed_ir = make_synthetic_room_ir(sr, rng)
            bleed = fftconvolve(bleed, bleed_ir, mode='full')[: len(clean)].astype(np.float32)
            augmented = augmented + bleed

    if rng.random() < ROOM_NOISE_PROB:
        augmented = add_background_noise(augmented, rng)

    return peak_limit(augmented)


