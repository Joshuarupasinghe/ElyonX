def gain_class(gain_db, threshold_db=1.0):
    if gain_db > threshold_db:
        return 'boost'
    if gain_db < -threshold_db:
        return 'cut'
    return 'flat'


def evaluate_param_predictions(records, split_name='test'):
    if len(records) == 0:
        print(f'No records for {split_name}.')
        return None

    pred, gt, names, insts = predict_records(records)
    rows = []
    detailed_rows = []

    for b_idx, band in enumerate(EQ_BANDS):
        p_gain = pred[:, b_idx, 0]
        g_gain = gt[:, b_idx, 0]
        p_freq = pred[:, b_idx, 1]
        g_freq = gt[:, b_idx, 1]
        p_q = pred[:, b_idx, 2]
        g_q = gt[:, b_idx, 2]

        gain_mae = float(np.mean(np.abs(p_gain - g_gain)))
        gain_rmse = float(np.sqrt(np.mean((p_gain - g_gain) ** 2)))
        freq_mape = float(np.mean(np.abs(p_freq - g_freq) / (g_freq + EPS)) * 100.0)
        q_mae = float(np.mean(np.abs(p_q - g_q)))

        pred_class = np.array([gain_class(x) for x in p_gain])
        gt_class = np.array([gain_class(x) for x in g_gain])
        cut_flat_boost_acc = float(np.mean(pred_class == gt_class))

        # Direction accuracy for non-flat labels only.
        nonflat = np.abs(g_gain) > 1.0
        if nonflat.any():
            direction_acc = float(np.mean(np.sign(p_gain[nonflat]) == np.sign(g_gain[nonflat])))
        else:
            direction_acc = np.nan

        rows.append({
            "Split": split_name,
            "Band": band['name'],
            "Gain MAE dB": gain_mae,
            "Gain RMSE dB": gain_rmse,
            "Gain within ±1dB": float(np.mean(np.abs(p_gain - g_gain) <= 1.0)),
            "Freq MAPE %": freq_mape,
            "Freq within ±10%": float(np.mean(np.abs(p_freq - g_freq) / (g_freq + EPS) <= 0.10)),
            "Q MAE": q_mae,
            "Cut/Flat/Boost Acc": cut_flat_boost_acc,
            "Direction Acc non-flat": direction_acc,
        })

    for i in range(len(records)):
        row = {"split": split_name, "instrument": insts[i], "filename": names[i]}
        for b_idx, band in enumerate(EQ_BANDS):
            row[f"{band['name']}_pred_gain_db"] = pred[i, b_idx, 0]
            row[f"{band['name']}_gt_gain_db"] = gt[i, b_idx, 0]
            row[f"{band['name']}_pred_freq_hz"] = pred[i, b_idx, 1]
            row[f"{band['name']}_gt_freq_hz"] = gt[i, b_idx, 1]
            row[f"{band['name']}_pred_q"] = pred[i, b_idx, 2]
            row[f"{band['name']}_gt_q"] = gt[i, b_idx, 2]
        detailed_rows.append(row)

    metrics_df = pd.DataFrame(rows)
    details_df = pd.DataFrame(detailed_rows)
    return metrics_df, details_df, pred, gt

