def params_to_normalized(params: np.ndarray):
    """Physical params (B, 3) -> normalized vector (B*3)."""
    out = []
    for i, band in enumerate(EQ_BANDS):
        gain_db, freq_hz, q = params[i]
        gain_norm = np.clip(gain_db / MAX_GAIN_DB, -1.0, 1.0)
        freq_norm = 2.0 * ((np.log(freq_hz) - np.log(band['min_hz'])) / (np.log(band['max_hz']) - np.log(band['min_hz']))) - 1.0
        q_norm = 2.0 * ((np.log(q) - np.log(Q_MIN)) / (np.log(Q_MAX) - np.log(Q_MIN))) - 1.0
        out.extend([gain_norm, freq_norm, q_norm])
    return np.asarray(out, dtype=np.float32)


def normalized_to_params(vec: np.ndarray):
    """Normalized vector (B*3) -> physical params (B, 3)."""
    vec = np.asarray(vec, dtype=np.float32).reshape(N_BANDS, 3)
    params = []
    for i, band in enumerate(EQ_BANDS):
        gain_norm = float(np.clip(vec[i, 0], -1.0, 1.0))
        freq_norm = float(np.clip(vec[i, 1], -1.0, 1.0))
        q_norm = float(np.clip(vec[i, 2], -1.0, 1.0))

        gain_db = gain_norm * MAX_GAIN_DB
        log_f = np.log(band['min_hz']) + ((freq_norm + 1.0) / 2.0) * (np.log(band['max_hz']) - np.log(band['min_hz']))
        log_q = np.log(Q_MIN) + ((q_norm + 1.0) / 2.0) * (np.log(Q_MAX) - np.log(Q_MIN))
        params.append([gain_db, float(np.exp(log_f)), float(np.exp(log_q))])
    return np.asarray(params, dtype=np.float32)


